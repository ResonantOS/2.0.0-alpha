function createPackageCard(title, body, items, { ordered = false } = {}) {
  const card = document.createElement("article");
  card.className = "addon-card";
  card.dataset.tone = "success";

  const header = document.createElement("div");
  header.className = "addon-card-header";
  const titleNode = document.createElement("strong");
  titleNode.textContent = title;
  const status = document.createElement("span");
  status.textContent = "Bounded";
  status.dataset.tone = "success";
  header.append(titleNode, status);

  const copy = document.createElement("p");
  copy.textContent = body;
  card.append(header, copy);

  const list = document.createElement(ordered ? "ol" : "ul");
  for (const item of items) {
    const row = document.createElement("li");
    if (/^(?:npm|public\/|docs\/|browser-first\/|\/Users\/|#)/.test(item)) {
      const code = document.createElement("code");
      code.textContent = item;
      row.append(code);
    } else {
      row.textContent = item;
    }
    list.append(row);
  }
  card.append(list);
  return card;
}

function renderHotRodRigTestResult(body, result) {
  body.replaceChildren();
  const status = document.createElement("p");
  status.className = "addons-status";
  status.dataset.tone = result?.passed ? "success" : "warning";
  const passed = Array.isArray(result?.checks) ? result.checks.filter((check) => check.passed).length : 0;
  const total = Array.isArray(result?.checks) ? result.checks.length : 0;
  status.textContent = `${result?.name || "Augmentor Hot Rod Rig add-on interface test"}: ${result?.status || "unknown"} · ${passed}/${total} checks passed.`;

  const summary = document.createElement("p");
  summary.textContent = result?.summary || "No test summary was returned.";

  const list = document.createElement("ul");
  for (const check of result?.checks ?? []) {
    const item = document.createElement("li");
    const label = document.createElement("strong");
    label.textContent = `${check.passed ? "PASS" : "FAIL"} · ${check.label}`;
    const detail = document.createElement("small");
    detail.textContent = [check.detail, check.evidence].filter(Boolean).join(" Evidence: ");
    item.append(label, detail);
    list.append(item);
  }

  const generated = document.createElement("small");
  generated.textContent = result?.generatedAt ? `Generated by ResonantOS bridge: ${result.generatedAt}` : "";
  body.append(status, summary, list, generated);
}

function createHotRodRigTestPanel({ bridgeRequest, getBridgeRequest } = {}) {
  const bridge = () => (typeof getBridgeRequest === "function" ? getBridgeRequest() : bridgeRequest);
  const panel = document.createElement("section");
  panel.className = "addon-draft-review agent-handoff-test";
  const header = document.createElement("div");
  header.className = "addon-draft-review-header";
  header.innerHTML = `
    <div>
      <span class="hero-kicker">Augmentor test</span>
      <h2>Augmentor Hot Rod Rig Test</h2>
      <p>Host-backed package check for the manifest, source evidence, truth boundary, browser-first routing, and screenshot-ready workspace surface.</p>
    </div>
  `;
  const body = document.createElement("div");
  body.className = "addon-draft-list";
  const status = document.createElement("p");
  status.className = "addons-status";
  status.textContent = "Waiting for the ResonantOS bridge to run the Hot Rod Rig package test...";
  body.append(status);
  panel.append(header, body);

  const run = async () => {
    const request = bridge();
    if (typeof request !== "function") {
      status.dataset.tone = "warning";
      status.textContent = "Bridge unavailable. Open this workspace through the live ResonantOS extension to run the test.";
      return;
    }
    status.textContent = "Running Augmentor Hot Rod Rig package test...";
    try {
      const result = await request("/addons/agent-handoff-kit/hot-rod-rig-test", { method: "GET" });
      renderHotRodRigTestResult(body, result);
    } catch (error) {
      status.dataset.tone = "error";
      status.textContent = `Hot Rod Rig package test unavailable: ${error instanceof Error ? error.message : String(error)}`;
    }
  };
  void run();
  return panel;
}

